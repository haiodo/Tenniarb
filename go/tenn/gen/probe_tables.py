# Regenerates go/tenn/grapheme_tables.go by probing the grapheme breaking of the Swift runtime on this machine.
# Usage, from the repository root: python3 go/tenn/gen/probe_tables.py > go/tenn/grapheme_tables.go && gofmt -w go/tenn/grapheme_tables.go
# Needs swiftc; the reference is the same one the differential fuzz uses (web/packages/core/fuzz/main.swift).
import base64, json, os, subprocess, sys, tempfile

root = os.path.normpath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
tmp = tempfile.mkdtemp(prefix="tenn-probe-")
ref = os.path.join(tmp, "tennref")
sources = [os.path.join(root, "Tenniarb/document/tenn", f + ".swift") for f in ("TennLexer", "TennLexerModel", "TennModel", "TennParser", "TennPrinter")]
subprocess.run(["swiftc", "-O", *sources, os.path.join(root, "web/packages/core/fuzz/main.swift"), "-o", ref], check=True, stdout=sys.stderr)

cps = [c for c in range(0x80, 0x30000) if not 0xD800 <= c <= 0xDFFF]


def joins(prefix):
    # A probe joins when the whole string stays one symbol token of one grapheme.
    strs = [prefix + chr(c) for c in cps]
    inp = "\n".join(base64.b64encode(s.encode()).decode() for s in strs) + "\n"
    out = subprocess.run([ref], input=inp, capture_output=True, text=True, check=True).stdout.split("\n")
    res = [json.loads(line) for line in out if line.startswith("{")]
    assert len(res) == len(strs)
    return {c for c, r, s in zip(cps, res, strs) if r["tokens"][0]["size"] == 1 and r["tokens"][0]["literal"] == s}


extend = joins("a")
pict = joins("\U0001F466‍") - extend
cons = joins("क्") - extend
# Conjunct linkers are few and hand-written in grapheme.go; the fuzz sweep (go run ./cmd/tennfuzz -sweep) checks them.


def ranges(s):
    rs = []
    for c in sorted(s):
        if rs and rs[-1][1] == c - 1:
            rs[-1][1] = c
        else:
            rs.append([c, c])
    return rs


def emit(name, s):
    body = "".join(f"\t{{0x{a:x}, 0x{b:x}}},\n" for a, b in ranges(s))
    return f"var {name} = [][2]rune{{\n{body}}}\n"


ver = subprocess.run(["swiftc", "--version"], capture_output=True, text=True).stdout.splitlines()[0]
print("package tenn\n")
print("// Extended_Pictographic and Indic_Conjunct_Break=Consonant, read from the grapheme breaking of the Swift")
print(f"// runtime ({ver}) by probing every scalar up to U+2FFFF. Generated by gen/probe_tables.py, do not edit.\n")
print(emit("extPictRanges", pict))
print(emit("indicConsonantRanges", cons), end="")
